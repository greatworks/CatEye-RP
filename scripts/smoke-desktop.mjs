import { _electron as electron, expect } from '@playwright/test';
import path from 'node:path';
import fs from 'node:fs/promises';
const root=path.resolve(import.meta.dirname,'..');
const executablePath=process.argv[2];
await fs.mkdir(path.join(root,'.build'),{recursive:true});
const userData=await fs.mkdtemp(path.join(root,'.build','smoke-user-'));
const app=await electron.launch({...(executablePath?{executablePath}:{args:[root]}),env:{...process.env,REA_HEADLESS_TEST:'1',REA_TEST_USER_DATA:userData}});
try {
  const page=await app.firstWindow();
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].webContents.setBackgroundThrottling(false));
  await page.getByText('REA Prototype Studio',{exact:false}).first().waitFor();
  await page.getByRole('button',{name:'Box',exact:true}).dblclick();
  await page.locator('.editor-widget').waitFor();
  await page.locator('.menubar').getByRole('button',{name:'Project',exact:true}).click();
  await page.locator('.dropdown-menu').getByRole('button',{name:'Rename project',exact:true}).click();
  const rename=page.getByRole('dialog',{name:'Project name',exact:true});
  await rename.getByRole('textbox').fill('Desktop verified project');
  await rename.getByRole('button',{name:'OK',exact:true}).click();
  await expect(page.locator('.titlebar')).toContainText('Desktop verified project');
  const widgetName=await page.getByRole('textbox',{name:'Widget name',exact:true}).inputValue();
  await page.getByRole('tab',{name:'Interactions',exact:true}).click();
  for(const [name,value] of [['First IF','First branch'],['Fallback ELSE','Wrong fallthrough']]){
    await page.getByRole('button',{name:'New interaction',exact:true}).click();
    const current=page.locator('.inspector-case').last();
    await current.getByRole('textbox',{name:'Case name',exact:true}).fill(name);
    await current.getByRole('button',{name:'Add action',exact:true}).click();
    await current.getByLabel('Action 1 type',{exact:true}).selectOption('setText');
    await current.getByLabel('Action 1 target',{exact:true}).selectOption({label:widgetName});
    await current.getByRole('textbox',{name:'Action value',exact:true}).fill(value);
  }
  const projectFile=path.join(userData,'native-save.rea.json');
  // Replace only the OS file-picker response; exercise real preload, IPC, validation and disk I/O.
  await app.evaluate(({dialog},file)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:file});},projectFile);
  await page.getByTitle('Save',{exact:true}).click();
  await expect(page.locator('.statusbar')).toContainText('Saved');
  const saved=JSON.parse(await fs.readFile(projectFile,'utf8'));
  if(saved.name!=='Desktop verified project'||saved.pages[0].widgets.length!==1)throw new Error('Native save did not preserve project');
  expect(saved.caseSelection).toBe('auto');
  expect(saved.pages[0].widgets[0].interactions.map(c=>c.isNewIfGroup)).toEqual([true,false]);
  await app.evaluate(({dialog},file)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[file]});},projectFile);
  await page.locator('.menubar').getByRole('button',{name:'File',exact:true}).click();
  await page.locator('.dropdown-menu').getByRole('button',{name:/^Open…/}).click();
  await expect(page.locator('.statusbar')).toContainText('Document opened');
  await page.getByTitle('Preview (F5)',{exact:true}).click();
  const previewBox=page.locator('.preview-page .widget').first();
  await previewBox.click();
  const caseMenu=page.getByRole('menu',{name:'Choose a case',exact:true});
  await expect(caseMenu).toBeVisible();
  await expect(previewBox).not.toHaveText('First branch');
  await caseMenu.getByRole('menuitem',{name:'First IF',exact:true}).click();
  await expect(previewBox).toHaveText('First branch');
  await expect(caseMenu).toHaveCount(0);
  await page.getByRole('button',{name:'Close preview',exact:true}).click();
  const htmlFile=path.join(userData,'native-export.html');
  await app.evaluate(({dialog},file)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:file});},htmlFile);
  await page.getByRole('button',{name:'Export HTML',exact:true}).click();
  await expect(page.locator('.statusbar')).toContainText('Exported');
  const html=await fs.readFile(htmlFile,'utf8');
  if(!html.includes('prototype-data')||!html.includes('Desktop verified project'))throw new Error('Native HTML export missing data');
  const result=await page.evaluate(()=>({title:document.title,widgets:document.querySelectorAll('.editor-widget').length,desktopApi:typeof window.desktop?.openDocument,nodeExposed:typeof window.require!=='undefined'}));
  if(result.widgets!==1||result.desktopApi!=='function'||result.nodeExposed)throw new Error(`Desktop smoke failure: ${JSON.stringify(result)}`);
  await fs.mkdir(path.join(root,'test-results'),{recursive:true});
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].webContents.invalidate());
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  const screenshot=await app.evaluate(async ({BrowserWindow})=>(await BrowserWindow.getAllWindows()[0].webContents.capturePage(undefined,{stayHidden:true})).toPNG().toString('base64'));
  if(!screenshot)throw new Error('Desktop capture returned no pixels');
  await fs.writeFile(path.join(root,'test-results','desktop-smoke.png'),Buffer.from(screenshot,'base64'));
  console.log(JSON.stringify({ok:true,...result,nativeRename:true,nativeSaveOpen:true,nativeExport:true,conditionalCasePersistenceAndPreview:true,caseMenuPersistenceAndSelection:true},null,2));
}finally{await app.close()}
